import json

import pytest

from app.db.repository import Record
from app.services.classification import llm
from app.services.confidence.calibrator import ConfidenceService, sha256_obj
from app.services.fields.mapping import FieldMapping, field_of_invention

FIELDS = {"abstract": "Quantum keys are distributed among smart grid nodes."}
ALLOWED = {"H04L0009080000", "H04L0009000000"}


def _sel(code, quote, source="abstract"):
    return {"code": code, "quotes": [{"source": source, "quote": quote, "claim_number": None}],
            "rationale": "r", "unresolved": []}


def test_llm_out_of_set_code_rejected():
    res, errs = llm.validate_output({"selections": [_sel("G06F0021000000", "Quantum keys")],
                                     "rejected_alternatives": [], "notes": ""}, ALLOWED, FIELDS)
    assert res is None and any("not in the supplied candidate set" in e for e in errs)


def test_llm_fabricated_quote_rejected():
    res, errs = llm.validate_output({"selections": [_sel("H04L0009080000", "keys are generated by lasers")],
                                     "rejected_alternatives": [], "notes": ""}, ALLOWED, FIELDS)
    assert res is None and errs


def test_llm_valid_output_accepted_and_schema_enum():
    res, errs = llm.validate_output({"selections": [_sel("H04L0009080000", "Quantum keys are distributed")],
                                     "rejected_alternatives": [], "notes": ""}, ALLOWED, FIELDS)
    assert res is not None and not errs
    schema = llm.output_schema(sorted(ALLOWED))
    assert schema["properties"]["selections"]["items"]["properties"]["code"]["enum"] == sorted(ALLOWED)
    assert "confidence" not in json.dumps(schema)


class FakeClient:
    def __init__(self, outputs):
        self.outputs = list(outputs)
        self.calls = 0

    def complete_json(self, system, user, schema):
        self.calls += 1
        assert "untrusted" in user
        return self.outputs.pop(0)


def test_llm_one_correction_then_degraded():
    bad = {"selections": [_sel("G06F0021000000", "x")], "rejected_alternatives": [], "notes": ""}
    client = FakeClient([bad, bad, bad])
    cands = [{"code": c} for c in sorted(ALLOWED)]
    res, reason = llm.run_constrained(client, FIELDS, [], cands, "m")
    assert res is None and "failed validation" in reason and client.calls == 2


def test_confidence_not_calibrated_without_artifact(tmp_path):
    svc = ConfidenceService(tmp_path, "fp")
    r = svc.confidence(3.2, input_mode="abstract_only", level="group")
    assert r.score is None and r.status == "not_calibrated"


def _write_artifact(tmp_path, fp, modes=("abstract_only",), tamper=False):
    manifest = {"calibrator_id": "cal-1", "method": "platt", "parameters": {"coef": 1.0, "intercept": 0.0},
                "compatibility": {"fingerprint_hash": fp}, "input_modes": list(modes), "requested_levels": ["group"],
                "status": "active"}
    manifest["artifact_sha256"] = sha256_obj({"method": "platt", "parameters": manifest["parameters"]})
    if tamper:
        manifest["parameters"]["coef"] = 5.0
    (tmp_path / "cal-1.json").write_text(json.dumps(manifest))
    (tmp_path / "ACTIVE.json").write_text(json.dumps({"manifest": "cal-1.json",
                                                      "artifact_sha256": manifest["artifact_sha256"]}))


def test_confidence_calibrated_incompatible_unsupported(tmp_path):
    _write_artifact(tmp_path, "fp")
    ok = ConfidenceService(tmp_path, "fp").confidence(0.0, input_mode="abstract_only", level="group")
    assert ok.status == "calibrated" and ok.score == pytest.approx(0.5)
    inc = ConfidenceService(tmp_path, "other").confidence(0.0, input_mode="abstract_only", level="group")
    assert inc.status == "incompatible_artifact" and inc.score is None
    uns = ConfidenceService(tmp_path, "fp").confidence(0.0, input_mode="abstract_with_optional_documents", level="group")
    assert uns.status == "unsupported_input_mode" and uns.score is None


def test_confidence_tampered_artifact_rejected(tmp_path):
    _write_artifact(tmp_path, "fp", tamper=True)
    r = ConfidenceService(tmp_path, "fp").confidence(1.0, input_mode="abstract_only", level="group")
    assert r.status == "not_calibrated" and r.score is None


def _rec(code, cls, cls_title, sub="H04L"):
    return Record(code=code, display_code=code, record_type="subgroup", title="t", title_raw=None, semantic_text="",
                  section_code=cls[0], section_title="S", class_code=cls, class_title=cls_title, subclass_code=sub,
                  subclass_title="", maingroup_code=None, maingroup_title=None, parent_code=None, ancestor_codes=[],
                  child_codes=[], depth=5, context_heading=None, titles=None, canonical_title=None,
                  is_duplicate_symbol=None, original_title=None, original_title_source=None, official_title=None)


def test_field_mapping():
    m = FieldMapping("1", {"H04": "COMMUNICATION"}, {})
    f = field_of_invention(m, [_rec("H04L0009080000", "H04", "ELECTRIC COMMUNICATION TECHNIQUE"),
                               _rec("B60L0053000000", "B60", "VEHICLES IN GENERAL", "B60L")], "")
    assert f["label"] == "COMMUNICATION" and f["mapping_key"] == "H04"
    assert f["additional_labels"][0]["label"] == "VEHICLES IN GENERAL"
    assert field_of_invention(m, [], "no support")["label"] == "UNDETERMINED"
